-- Consultations, chat, clinical access, documents, prescriptions.

create table public.consultations (
  appointment_id uuid primary key references public.appointments (id) on delete cascade,
  patient_joined_at timestamptz,
  doctor_joined_at timestamptz,
  started_at timestamptz,
  ended_at timestamptz,
  ended_by uuid references public.profiles (id),
  duration_seconds integer generated always as (
    case when started_at is not null and ended_at is not null
      then greatest(0, extract(epoch from (ended_at - started_at))::integer) end
  ) stored,
  last_activity_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.consultation_messages (
  id uuid primary key default gen_random_uuid(),
  appointment_id uuid not null references public.appointments (id) on delete cascade,
  sender_id uuid not null references public.profiles (id),
  -- Generated by the sender's browser; makes retries idempotent and lets the UI de-duplicate.
  client_id uuid not null,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  unique (sender_id, client_id)
);
create index consultation_messages_appt_idx on public.consultation_messages (appointment_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Clinical access: treating relationship OR explicit grant.
-- ---------------------------------------------------------------------------
create table public.clinical_access_grants (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.patient_profiles (user_id) on delete cascade,
  doctor_id uuid not null references public.doctor_profiles (user_id) on delete cascade,
  source text not null check (source in ('patient_share', 'admin_referral')),
  reason text not null check (char_length(reason) between 3 and 1000),
  granted_by uuid not null references public.profiles (id),
  expires_at timestamptz,
  revoked_at timestamptz,
  revoked_by uuid references public.profiles (id),
  created_at timestamptz not null default now()
);
create index clinical_access_grants_pair_idx on public.clinical_access_grants (doctor_id, patient_id);

create function public.doctor_has_clinical_access(p_doctor uuid, p_patient uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_approved_doctor(p_doctor) and (
    exists (
      select 1 from public.appointments a
      where a.doctor_id = p_doctor and a.patient_id = p_patient
        and a.status in ('confirmed', 'in_progress', 'completed', 'no_show')
    )
    or exists (
      select 1 from public.clinical_access_grants g
      where g.doctor_id = p_doctor and g.patient_id = p_patient
        and g.revoked_at is null and (g.expires_at is null or g.expires_at > now())
    )
  )
$$;

create function public.can_read_patient_clinical(p_patient uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() = p_patient
      or public.doctor_has_clinical_access(auth.uid(), p_patient)
      or public.has_permission('clinical.read')
$$;

create function public.is_appointment_participant(p_appointment uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.appointments a
    where a.id = p_appointment and auth.uid() in (a.patient_id, a.doctor_id)
  )
$$;

-- Chat is open from the join window until the consultation completes.
create function public.can_post_message(p_appointment uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.appointments a
    where a.id = p_appointment
      and auth.uid() in (a.patient_id, a.doctor_id)
      and (
        a.status = 'in_progress'
        or (a.status = 'confirmed'
            and now() >= a.start_at - make_interval(mins => coalesce(
              (public.setting('consultation') ->> 'join_open_minutes_before')::integer, 10))
            and now() <= a.end_at + make_interval(mins => coalesce(
              (public.setting('consultation') ->> 'join_close_minutes_after')::integer, 30)))
      )
  )
$$;

-- ---------------------------------------------------------------------------
-- Medical documents (private bucket `medical-documents`, path <patient_id>/<uuid>)
-- ---------------------------------------------------------------------------
create table public.medical_documents (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.patient_profiles (user_id) on delete cascade,
  appointment_id uuid references public.appointments (id) on delete set null,
  uploaded_by uuid not null references public.profiles (id),
  category public.document_category not null default 'other',
  title text not null check (char_length(title) between 1 and 200),
  storage_path text not null unique,
  file_name text not null check (char_length(file_name) <= 255),
  mime_type text not null check (mime_type in (
    'application/pdf', 'image/jpeg', 'image/png', 'image/webp', 'image/heic'
  )),
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 26214400),
  status text not null default 'pending' check (status in ('pending', 'available', 'deleted')),
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  check (storage_path like patient_id::text || '/%')
);
create index medical_documents_patient_idx on public.medical_documents (patient_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Prescriptions (consultation record + structured medication items).
-- Finalised versions are immutable; amendments create a new version.
-- ---------------------------------------------------------------------------
create table public.prescriptions (
  id uuid primary key default gen_random_uuid(),
  appointment_id uuid not null references public.appointments (id),
  patient_id uuid not null references public.patient_profiles (user_id),
  doctor_id uuid not null references public.doctor_profiles (user_id),
  version integer not null default 1 check (version >= 1),
  status public.prescription_status not null default 'draft',
  supersedes_id uuid references public.prescriptions (id),
  presenting_symptoms text check (char_length(presenting_symptoms) <= 5000),
  clinical_observations text check (char_length(clinical_observations) <= 5000),
  relevant_history text check (char_length(relevant_history) <= 5000),
  diagnosis text check (char_length(diagnosis) <= 2000),
  treatment_plan text check (char_length(treatment_plan) <= 5000),
  advice text check (char_length(advice) <= 5000),
  follow_up text check (char_length(follow_up) <= 1000),
  amendment_reason text check (char_length(amendment_reason) <= 1000),
  doctor_snapshot jsonb,
  patient_snapshot jsonb,
  content_hash text,
  finalized_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (appointment_id, version),
  check (status = 'draft' or (finalized_at is not null and content_hash is not null))
);
create unique index prescriptions_one_draft on public.prescriptions (appointment_id) where status = 'draft';
create unique index prescriptions_one_final on public.prescriptions (appointment_id) where status = 'final';
create index prescriptions_patient_idx on public.prescriptions (patient_id, created_at desc);
create trigger prescriptions_updated_at before update on public.prescriptions
  for each row execute function public.set_updated_at();

create table public.prescription_items (
  id uuid primary key default gen_random_uuid(),
  prescription_id uuid not null references public.prescriptions (id) on delete cascade,
  position smallint not null default 0,
  medication_name text not null check (char_length(medication_name) between 1 and 200),
  strength text check (char_length(strength) <= 100),
  dosage_form text check (char_length(dosage_form) <= 100),
  dose text check (char_length(dose) <= 100),
  route text check (char_length(route) <= 100),
  frequency text check (char_length(frequency) <= 100),
  duration text check (char_length(duration) <= 100),
  instructions text check (char_length(instructions) <= 1000)
);
create index prescription_items_rx_idx on public.prescription_items (prescription_id, position);

create function public.guard_prescription_immutability()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'draft' then
      raise exception 'IMMUTABLE: finalised prescriptions cannot be deleted' using errcode = 'P0001';
    end if;
    return old;
  end if;
  if old.status = 'superseded' then
    raise exception 'IMMUTABLE: superseded prescriptions cannot change' using errcode = 'P0001';
  end if;
  if old.status = 'final' then
    -- The only permitted change to a final version is being superseded by an amendment.
    if new.status <> 'superseded' or (to_jsonb(new) - 'status' - 'updated_at') <> (to_jsonb(old) - 'status' - 'updated_at') then
      raise exception 'IMMUTABLE: finalised prescriptions cannot change; create an amendment' using errcode = 'P0001';
    end if;
  end if;
  return new;
end;
$$;
create trigger prescriptions_immutability before update or delete on public.prescriptions
  for each row execute function public.guard_prescription_immutability();

create function public.guard_prescription_items()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_status public.prescription_status;
begin
  select status into v_status from public.prescriptions
  where id = coalesce(new.prescription_id, old.prescription_id);
  -- Parent row already gone (cascade delete of a draft) or still a draft: allowed.
  if v_status is not null and v_status <> 'draft' then
    raise exception 'IMMUTABLE: items of a finalised prescription cannot change' using errcode = 'P0001';
  end if;
  return coalesce(new, old);
end;
$$;
create trigger prescription_items_guard before insert or update or delete on public.prescription_items
  for each row execute function public.guard_prescription_items();
